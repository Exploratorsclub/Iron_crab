import base58

# Creator bytes from bonding curve offset 49-80
creator_bytes = bytes([
    0xc4, 0xd5, 0xed, 0x0e, 0xa6, 0x11, 0xf1, 0xad,
    0x3c, 0xbd, 0x8d, 0x27, 0x8a, 0xe7, 0x7f, 0xb1,
    0x79, 0x23, 0xb4, 0xcd, 0xd3, 0x72, 0x3c, 0x87,
    0xb6, 0x0d, 0xc2, 0xd4, 0x07, 0x49, 0xe6, 0xc2
])

creator_base58 = base58.b58encode(creator_bytes).decode()
print(f"Creator pubkey: {creator_base58}")
